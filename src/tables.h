/*
 * One block per device family (EP1810 / EP1800I, EP910 / EP900I, EP610 / EP600I).
 *   pair_kind, pair_n   what each pair of array lines carries, per array (the EP1810 has
 *                       four arrays, one per quadrant): 1 = dedicated input or clock pin
 *                       (pin record n), 2 = the pin or the feedback of logic cell n,
 *                       chosen by that cell, 3 = the feedback of global logic cell n,
 *                       4 = the pin of global logic cell n (global bus).
 *                       Line 2i is the complemented signal of pair i, line 2i+1 the true one.
 *   cell_vp             pin record of each logic cell; cell_clk its clock pin record
 *   pin_a, pin_b        package pin name of each pin record in the two packages
 *   bitbase, tag7, tag6 layout of the POF programming image
 */
